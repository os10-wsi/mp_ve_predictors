#!/usr/bin/env bash
# ThermoMPNN saturation scans over a directory of PDB files, as an LSF array.
#
#   bash scripts/submit_thermompnn.sh --structures /path/to/structures
#   bash scripts/submit_thermompnn.sh --structures ... --dry-run
#
# custom_inference.py generates the site-saturation mutation list itself, so
# one PDB in gives every substitution at every position out. One task per
# structure: the scheduler runs them in parallel and a failure costs that
# structure rather than the batch.
#
# This drives an upstream checkout through an environment module, so it is
# deliberately separate from `vepbench run`, which uses the managed
# environments in envs/.
set -euo pipefail

STRUCTURES=""
THERMOMPNN="${THERMOMPNN_DIR:-}"
OUT_DIR=""
MODULE="${THERMOMPNN_MODULE:-HGI/softpack/users/rc30/ThermoMPNN/2}"
GROUP="${LSB_DEFAULT_PROJECT:-team354}"
QUEUE="${VEPBENCH_QUEUE:-gpu}"
CHAIN="A"
MEM_MB=8000
WALLTIME="12:00"
MAX_PARALLEL="${VEPBENCH_MAX_PARALLEL:-10}"
DRY_RUN=0
MODEL_PATH=""

usage() { sed -n '2,15p' "$0"; exit "${1:-0}"; }

while [ $# -gt 0 ]; do
  case "$1" in
    --structures)    STRUCTURES="$2"; shift 2 ;;
    --thermompnn)    THERMOMPNN="$2"; shift 2 ;;
    --out-dir)       OUT_DIR="$2"; shift 2 ;;
    --module)        MODULE="$2"; shift 2 ;;
    --group)         GROUP="$2"; shift 2 ;;
    --queue)         QUEUE="$2"; shift 2 ;;
    --chain)         CHAIN="$2"; shift 2 ;;
    --mem)           MEM_MB="$2"; shift 2 ;;
    --time)          WALLTIME="$2"; shift 2 ;;
    --max-parallel)  MAX_PARALLEL="$2"; shift 2 ;;
    --model-path)    MODEL_PATH="$2"; shift 2 ;;
    --dry-run)       DRY_RUN=1; shift ;;
    -h|--help)       usage 0 ;;
    *) echo "unknown option: $1" >&2; usage 2 ;;
  esac
done

if [ -z "$STRUCTURES" ]; then
  echo "error: --structures DIR is required" >&2; exit 2
fi
STRUCTURES="$(cd "$STRUCTURES" && pwd)"
if [ -z "$THERMOMPNN" ]; then
  # Alongside the structures directory is where it sits in practice.
  for candidate in "$STRUCTURES/../ThermoMPNN" "$PWD/third_party/ThermoMPNN"; do
    if [ -d "$candidate" ]; then THERMOMPNN="$(cd "$candidate" && pwd)"; break; fi
  done
fi
if [ -z "$THERMOMPNN" ] || [ ! -f "$THERMOMPNN/analysis/custom_inference.py" ]; then
  echo "error: could not find analysis/custom_inference.py." >&2
  echo "       Pass --thermompnn /path/to/ThermoMPNN or set THERMOMPNN_DIR." >&2
  exit 2
fi
[ -n "$OUT_DIR" ] || OUT_DIR="$STRUCTURES/../thermompnn_out"
mkdir -p "$OUT_DIR" "$OUT_DIR/logs"
OUT_DIR="$(cd "$OUT_DIR" && pwd)"

STAMP="$(date -u +%Y%m%dT%H%M%SZ)"
LIST="$OUT_DIR/structures-${STAMP}.txt"
# Snapshot the file list: a queued array reads it as each task starts, which
# can be hours later, and the directory may have changed by then.
find "$STRUCTURES" -maxdepth 1 -name '*.pdb' | sort > "$LIST"
N="$(wc -l < "$LIST")"
if [ "$N" -lt 1 ]; then
  echo "error: no .pdb files in $STRUCTURES" >&2; exit 2
fi

JOB_SCRIPT="$OUT_DIR/thermompnn-${STAMP}.sh"
{
  echo "#!/usr/bin/env bash"
  echo "# Generated by scripts/submit_thermompnn.sh on ${STAMP}."
  echo "set -euo pipefail"
  echo
  echo "module load $(printf '%q' "$MODULE")"
  echo
  echo "PDB=\"\$(sed -n \"\${LSB_JOBINDEX}p\" $(printf '%q' "$LIST"))\""
  echo 'if [ -z "$PDB" ]; then echo "no structure at index $LSB_JOBINDEX" >&2; exit 1; fi'
  echo 'ACCESSION="$(basename "$PDB" .pdb)"'
  echo
  echo 'echo "host      : $(hostname)"'
  echo 'echo "structure : $PDB"'
  echo 'echo "started   : $(date -u +%Y-%m-%dT%H:%M:%SZ)"'
  echo
  printf 'python %q \\\n' "$THERMOMPNN/analysis/custom_inference.py"
  echo '  --pdb "$PDB" \'
  printf '  --chain %q \\\n' "$CHAIN"
  if [ -n "$MODEL_PATH" ]; then printf '  --model_path %q \\\n' "$MODEL_PATH"; fi
  printf '  --out_dir %q\n' "$OUT_DIR"
  echo
  echo 'echo "finished  : $(date -u +%Y-%m-%dT%H:%M:%SZ)"'
  printf 'ls -l %q/ThermoMPNN_inference_"$ACCESSION".csv\n' "$OUT_DIR"
} > "$JOB_SCRIPT"
chmod +x "$JOB_SCRIPT"

BSUB=(bsub -J "thermompnn[1-${N}]%${MAX_PARALLEL}" -G "$GROUP" -q "$QUEUE"
      -gpu "num=1:j_exclusive=yes"
      -M "$MEM_MB" -R "select[mem>$MEM_MB] rusage[mem=$MEM_MB] span[hosts=1]"
      -W "$WALLTIME"
      -o "$OUT_DIR/logs/%J.%I.out" -e "$OUT_DIR/logs/%J.%I.err"
      bash "$JOB_SCRIPT")

echo "=== job script ==="
echo "$JOB_SCRIPT"
sed 's/^/  /' "$JOB_SCRIPT"
echo
echo "=== submit command ==="
printf '  '; printf '%q ' "${BSUB[@]}"; echo
echo
echo "structures : $N (from $LIST)"
echo "outputs    : $OUT_DIR/ThermoMPNN_inference_<accession>.csv"
echo "logs       : $OUT_DIR/logs/<jobid>.<task>.{out,err}"

if [ "$DRY_RUN" = "1" ]; then echo; echo "--dry-run: nothing submitted."; exit 0; fi
command -v bsub >/dev/null 2>&1 || {
  echo >&2; echo "error: bsub is not on PATH. Run the job script directly:" >&2
  echo "  LSB_JOBINDEX=1 bash $JOB_SCRIPT" >&2; exit 1
}
echo
"${BSUB[@]}"
