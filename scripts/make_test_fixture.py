#!/usr/bin/env python3
"""Build an idealised alpha-helix PDB used only as a geometry test fixture.

This is NOT a structural model of any protein. It exists so the PDB reader,
the UniProt renumbering and the Shrake-Rupley surface code can be tested
deterministically and offline. Never use it as a structure input for a real
prediction.
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

# Approximate helical coordinates per backbone atom, as
# (radius, phase offset in degrees, rise offset in angstroms, element),
# relative to the C-alpha helix.
ATOM_GEOMETRY = {
    "N": (1.55, -28.3, -0.92, "N"),
    "CA": (2.27, 0.0, 0.0, "C"),
    "C": (1.68, 25.6, 0.69, "C"),
    "O": (2.02, 44.0, 1.20, "O"),
    "CB": (3.35, -12.0, -0.65, "C"),
}
RISE_PER_RESIDUE = 1.5
TWIST_PER_RESIDUE = 100.0

ONE_TO_THREE = {
    "A": "ALA", "R": "ARG", "N": "ASN", "D": "ASP", "C": "CYS", "Q": "GLN",
    "E": "GLU", "G": "GLY", "H": "HIS", "I": "ILE", "L": "LEU", "K": "LYS",
    "M": "MET", "F": "PHE", "P": "PRO", "S": "SER", "T": "THR", "W": "TRP",
    "Y": "TYR", "V": "VAL",
}


def build(sequence: str, start: int, b_factor: float) -> str:
    lines = [
        "REMARK   1 SYNTHETIC IDEALISED ALPHA HELIX - TEST FIXTURE ONLY",
        "REMARK   1 THIS IS NOT A STRUCTURAL MODEL AND MUST NOT BE USED FOR PREDICTION",
        "REMARK   1 GENERATED BY scripts/make_test_fixture.py",
    ]
    serial = 1
    for index, aa in enumerate(sequence):
        resnum = start + index
        angle = math.radians(TWIST_PER_RESIDUE * index)
        z0 = RISE_PER_RESIDUE * index
        for atom_name, (radius, phase, dz, element) in ATOM_GEOMETRY.items():
            if aa == "G" and atom_name == "CB":
                continue
            theta = angle + math.radians(phase)
            lines.append(
                f"ATOM  {serial:5d} {atom_name:<4s}{ONE_TO_THREE[aa]:>4s} A{resnum:4d}    "
                f"{radius * math.cos(theta):8.3f}{radius * math.sin(theta):8.3f}"
                f"{z0 + dz:8.3f}  1.00{b_factor:6.2f}          {element:>2s}"
            )
            serial += 1
    lines += ["TER", "END"]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sequence", required=True)
    parser.add_argument("--start", type=int, default=1,
                        help="residue number of the first residue")
    parser.add_argument("--b-factor", type=float, default=85.0)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build(args.sequence.strip().upper(), args.start, args.b_factor))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
